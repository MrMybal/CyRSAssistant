"""Compile, validate and stage the application-owned CyDoc manual."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def inputs(root=ROOT):
    names = ["CMakeLists.txt", "cydoc.config.json", "package.json", "package-lock.json",
             "tools/cydoc.lock.json", "tools/build_help.py", "tools/export_help.mjs",
             "tools/docs_reader.mjs", "tools/help_redirect.mjs", "docs/reader.html", "docs/reader.css"]
    for folder in ("docs/content", "assets", "src", "companion", "vendor/cydoc"):
        names.extend(p.relative_to(root).as_posix() for p in (root / folder).rglob("*")
                     if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc")
    return sorted(set(names))

def fingerprint(root=ROOT):
    digest = hashlib.sha256()
    for name in inputs(root):
        digest.update(name.encode("utf-8") + b"\0" + (root / name).read_bytes() + b"\0")
    return digest.hexdigest()

def native_header(manifest, path):
    books = []
    for locale in manifest["locales"]:
        pages = []
        for page in manifest["pages"]:
            if page["locale"] != locale["code"]: continue
            pages.append({k: page[k] for k in ("id", "title", "description", "kind", "headings", "anchors") if k in page} |
                         {"media": re.findall(r'data-cydoc-id="([^"]+)"', page["html"])})
        books.append({"code": locale["code"], "pages": pages})
    lines = ["// Generated by the CyDoc help build. Do not edit.", "#pragma once", "#include <cstddef>",
             "namespace cyrs::manual_data {", "struct Document { const char *const *chunks; size_t count; };"]
    for i, book in enumerate(books):
        encoded = json.dumps(book, ensure_ascii=False, separators=(",", ":"))
        lines.append(f"inline constexpr const char *document_{i}[] = {{")
        lines.extend("    " + json.dumps(encoded[j:j+4096], ensure_ascii=False) + "," for j in range(0, len(encoded), 4096))
        lines.append("};")
    lines.append("inline constexpr Document documents[] = {")
    lines.extend(f"    {{document_{i}, sizeof(document_{i}) / sizeof(const char *)}}," for i in range(len(books)))
    lines.extend(["};", "}", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")

def validate(root=ROOT):
    output = root / "build/help"
    stamp = json.loads((output / "build-inputs.json").read_text(encoding="utf-8"))
    if stamp["sha256"] != fingerprint(root): raise ValueError("CyDoc help is stale. Run python tools/build_help.py.")
    actual = {p.relative_to(output).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in output.rglob("*") if p.is_file() and p.name != "build-inputs.json"}
    if actual != stamp["files"]: raise ValueError("CyDoc export resources changed or are missing. Regenerate the manual.")
    manifest = json.loads((output / "manifest.json").read_text(encoding="utf-8"))
    report = json.loads((output / "translation-report.json").read_text(encoding="utf-8"))
    if any(report[key] for key in ("missing", "outdated", "untracked")):
        raise ValueError("CyDoc translations must be complete and tracked")
    if manifest["defaultLocale"] != "en": raise ValueError("English must remain the default")
    modules = sorted(p.name for p in output.glob("media-*.js"))
    if modules != ["media-image.js"]: raise ValueError("Only the image module belongs in this product")
    for required in ("index.html", "index.en.html", "index.fr.html", "viewer.js", "data.js", "viewer.css", "reader.css",
                     "legacy.js", "LICENSE.CyDoc.txt", "assets/screenshots/chat-preview.png", "assets/screenshots/connection-preview.png"):
        if not (output / required).is_file(): raise ValueError("Missing CyDoc export file: " + required)
    for file in output.rglob("*"):
        if file.is_symlink(): raise ValueError("Documentation cannot contain filesystem links")
    return output

def build(root=ROOT, header=None, check=False):
    lock = json.loads((root / "tools/cydoc.lock.json").read_text(encoding="utf-8"))
    archive = root / lock["package"]
    if hashlib.sha256(archive.read_bytes()).hexdigest() != lock["sha256"]: raise ValueError("CyDoc package hash mismatch")
    installed = root / "node_modules/cydoc/package.json"
    if not installed.is_file(): raise ValueError("Install build dependencies with npm ci --omit=peer")
    if json.loads(installed.read_text(encoding="utf-8"))["version"] != lock["version"]: raise ValueError("Wrong installed CyDoc version")
    node = shutil.which("node")
    if not node or int(subprocess.check_output([node, "--version"], text=True).lstrip("v").split(".")[0]) < 22:
        raise ValueError("Node.js 22+ is required only to generate documentation")
    config = json.loads((root / "cydoc.config.json").read_text(encoding="utf-8"))
    version = re.search(r"project\(CyRSAssistant VERSION ([0-9.]+)", (root / "CMakeLists.txt").read_text(encoding="utf-8-sig")).group(1)
    if config["version"] != version or config["modules"] != ["image"]: raise ValueError("CyDoc version/modules differ from the product")
    output = (root / config["out"]).resolve()
    if output != (root / "build/help").resolve(): raise ValueError("Help output must be the dedicated build/help directory")
    if output.exists(): shutil.rmtree(output)
    subprocess.run([node, str(root / "tools/export_help.mjs"), "check" if check else "build"], cwd=root, check=True)
    manifest = json.loads((output / "manifest.json").read_text(encoding="utf-8"))
    (output / "build-inputs.json").write_text(json.dumps({"generator": "CyDoc " + lock["version"], "commit": lock["commit"], "sha256": fingerprint(root), "files": {p.relative_to(output).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in output.rglob("*") if p.is_file() and p.name != "build-inputs.json"}}, indent=2) + "\n", encoding="utf-8")
    validate(root)
    native_header(manifest, header or root / "build/generated/manual_data.hpp")
    print("CyRSAssistant: local CyDoc export, translations and selected modules verified")
    return output

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    build(header=args.header, check=args.check)
