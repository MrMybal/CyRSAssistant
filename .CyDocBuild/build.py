"""Generate and validate the complete application-owned CyDoc reader."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import time

ROOT = Path(__file__).resolve().parents[1]


def inputs(root=ROOT):
    work = root / ".CyDocBuild"
    names = ["CMakeLists.txt", "companion/transport.py"]
    names.extend(".CyDocBuild/" + name for name in ("cydoc.config.json", "cydoc.lock.json", "package.json", "package-lock.json", "build.py", "export.mjs", "check.mjs", "reader.mjs", "reader.html", "reader.css", "redirect.mjs", "api-revisions.json"))
    for folder in ("manual", "assets", "vendor"):
        names.extend(path.relative_to(root).as_posix() for path in (work / folder).rglob("*") if path.is_file())
    return sorted(set(names))


def fingerprint(root=ROOT):
    digest = hashlib.sha256()
    for name in inputs(root):
        digest.update(name.encode("utf-8") + b"\0" + (root / name).read_bytes() + b"\0")
    return digest.hexdigest()


def output_files(output):
    result = {}
    for path in output.rglob("*"):
        if path.is_symlink(): raise ValueError("Documentation cannot contain filesystem links")
        if path.is_file(): result[path.relative_to(output).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


def native_header(manifest, path):
    books = []
    for locale in manifest["locales"]:
        pages = []
        for page in manifest["pages"]:
            if page["locale"] != locale["code"]: continue
            pages.append({k: page[k] for k in ("id", "title", "description", "kind", "headings", "anchors") if k in page} |
                         {"media": re.findall(r'data-cydoc-id="([^"]+)"', page["html"])})
        books.append({"code": locale["code"], "pages": pages, "aliases": manifest.get("aliases", {})})
    lines = ["// Generated by the CyDoc help build. Do not edit.", "#pragma once", "#include <cstddef>",
             "namespace cyrs::manual_data {", "struct Document { const char *const *chunks; size_t count; };"]
    for i, book in enumerate(books):
        encoded = json.dumps(book, ensure_ascii=False, separators=(",", ":"))
        lines.append(f"inline constexpr const char *document_{i}[] = {{")
        lines.extend("    " + json.dumps(encoded[j:j+4096], ensure_ascii=False) + "," for j in range(0, len(encoded), 4096))
        lines.append("};")
    lines.append("inline constexpr Document documents[] = {")
    lines.extend(f"    {{document_{i}, sizeof(document_{i}) / sizeof(const char *)}}," for i in range(len(books)))
    lines.extend(["};", "}", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def validate(root=ROOT):
    work = root / ".CyDocBuild"
    output = root / "Documentation"
    stamp = json.loads((work / "generated/build-inputs.json").read_text(encoding="utf-8"))
    if stamp["sha256"] != fingerprint(root): raise ValueError("CyDoc help is stale. Run python .CyDocBuild/build.py.")
    if output_files(output) != stamp["files"]: raise ValueError("CyDoc export resources changed or are missing")
    data = json.loads((output / "DocData/manifest.json").read_text(encoding="utf-8"))
    report = json.loads((output / "DocData/translation-report.json").read_text(encoding="utf-8"))
    if any(report[key] for key in ("missing", "outdated", "untracked")): raise ValueError("English and French must be complete and current")
    if data["defaultLocale"] != "en" or [locale["code"] for locale in data["locales"]] != ["en", "fr"]: raise ValueError("Unexpected published locales")
    if any(page.get("kind") == "source" or page["id"].startswith("source-") for page in data["pages"]): raise ValueError("Raw implementation in human documentation")
    if sorted(path.name for path in (output / "DocData").glob("media-*.js")) != ["media-image.js"]: raise ValueError("Unexpected media modules")
    for name in ("Documentation.html", "DocAI.md", "DocData/data.js", "DocData/viewer.js", "DocData/media-image.js", "DocData/assets/cyrsassistant-logo-turquoise.png"):
        if not (output / name).is_file(): raise ValueError("Missing documentation file: " + name)
    return output


def build(root=ROOT, header=None, check=False):
    work = root / ".CyDocBuild"
    lock = json.loads((work / "cydoc.lock.json").read_text(encoding="utf-8"))
    archive = work / lock["package"]
    if hashlib.sha256(archive.read_bytes()).hexdigest() != lock["sha256"]: raise ValueError("CyDoc package hash mismatch")
    installed = work / "node_modules/cydoc"
    if not (installed / "package.json").is_file(): raise ValueError("Install documentation dependencies with npm --prefix .CyDocBuild ci --omit=peer")
    # CyDoc keeps version 0.1.0 across these revisions; compare actual package bytes.
    with tarfile.open(archive) as package:
        for name in ("dist/index.js", "dist/viewer.js", "tools/build.mjs"):
            if (installed / name).read_bytes() != package.extractfile("package/" + name).read(): raise ValueError("Installed CyDoc does not match the pinned revision")
    node = shutil.which("node")
    if not node or int(subprocess.check_output([node, "--version"], text=True).lstrip("v").split(".")[0]) < 22: raise ValueError("Node.js 22+ is a build-time requirement")
    config = json.loads((work / "cydoc.config.json").read_text(encoding="utf-8"))
    version = re.search(r"project\(CyRSAssistant VERSION ([0-9.]+)", (root / "CMakeLists.txt").read_text(encoding="utf-8-sig")).group(1)
    output = root / "Documentation"
    if config["version"] != version or config["modules"] != ["image"]: raise ValueError("Documentation version/modules differ from the product")
    if (work / config["out"]).resolve() != root.resolve() / "Documentation": raise ValueError("Unexpected output directory")
    stage = work / "generated/export"
    if stage.resolve() != root.resolve() / ".CyDocBuild/generated/export": raise ValueError("Unexpected staging directory")
    if stage.exists(): shutil.rmtree(stage)
    subprocess.run([node, str(work / "export.mjs"), *( ["--check"] if check else [])], cwd=work, check=True)
    subprocess.run([node, str(work / "check.mjs"), str(stage)], cwd=work, check=True)
    data = json.loads((stage / "DocData/manifest.json").read_text(encoding="utf-8"))
    stamp_path = work / "generated/build-inputs.json"
    if output.exists():
        if output.resolve() != root.resolve() / "Documentation" or output.is_symlink(): raise ValueError("Unsafe documentation destination")
        previous = json.loads(stamp_path.read_text(encoding="utf-8")) if stamp_path.exists() else {}
        if output_files(output) != previous.get("files"):
            backup = work / "internal/exports" / (str(time.time_ns()) + "-previous")
            backup.parent.mkdir(parents=True, exist_ok=True)
            output.rename(backup)
        else: shutil.rmtree(output)
    stage.rename(output)
    stamp_path.write_text(json.dumps({"generator": "CyDoc " + lock["version"], "commit": lock["commit"], "sha256": fingerprint(root), "files": output_files(output)}, indent=2) + "\n", encoding="utf-8")
    validate(root)
    native_header(data, header or root / "build/generated/manual_data.hpp")
    print("CyRSAssistant manual: " + str(output / "Documentation.html"))
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    build(header=args.header, check=args.check)
